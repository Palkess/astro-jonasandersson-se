<p>
    Det här är min personliga portfolio. Webbplatsen har inga formulär, inga konton och ingen
    inloggning. Här beskriver jag vilka uppgifter som behandlas när du besöker den, och vilka som
    inte gör det.
</p>

<h2>Personuppgiftsansvarig</h2>
<p>Jonas Andersson är personuppgiftsansvarig för webbplatsen jonasandersson.se.</p>

<h2>Vilka uppgifter som samlas in</h2>
<p>
    Webbplatsen samlar inte själv in några personuppgifter om dig, och jag lagrar ingen databas med
    besökarnas uppgifter.
</p>
<p>
    Webbplatsen ligger hos GitHub Pages. När du besöker den kan GitHub logga tekniska uppgifter,
    till exempel din IP-adress, för att driva och skydda tjänsten. Det regleras av GitHubs egen
    integritetspolicy, som jag inte råder över.
</p>

<h2>Cookies och analys</h2>
<p>
    Jag använder Google Analytics via Google Tag Manager för att förstå hur webbplatsen används,
    till exempel vilka sidor som besöks mest. Det laddas först efter att du har samtyckt i
    cookie-rutan. Väljer du att inte samtycka laddas ingen analys, inga analyscookies sätts och
    inget skickas till Google.
</p>
<p>
    Ditt val sparas lokalt i din webbläsare. Du kan när som helst ändra dig genom att rensa
    webbplatsdata för jonasandersson.se i din webbläsare, varefter frågan ställs på nytt.
</p>

