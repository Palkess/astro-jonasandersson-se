<p>
    This is my personal portfolio. The site has no forms, no accounts and no login. This page
    describes what data is processed when you visit it, and what isn't.
</p>

<h2>Data controller</h2>
<p>Jonas Andersson is the data controller for the website jonasandersson.se.</p>

<h2>What data is collected</h2>
<p>
    The site itself collects no personal data about you, and I keep no database of visitors'
    details.
</p>
<p>
    The site is hosted on GitHub Pages. When you visit it, GitHub may log technical data such as
    your IP address to operate and protect the service. That is governed by GitHub's own privacy
    statement, which I have no control over.
</p>

<h2>Cookies and analytics</h2>
<p>
    I use Google Analytics through Google Tag Manager to understand how the site is used, for
    example which pages are visited most. It only loads after you have given your consent in the
    cookie banner. If you decline, no analytics load, no analytics cookies are set and nothing is
    sent to Google.
</p>
<p>
    Your choice is stored locally in your browser. You can change your mind at any time by clearing
    the site data for jonasandersson.se in your browser, after which you'll be asked again.
</p>

<h2>Your rights</h2>
<p>
    Under the GDPR you have the right to request access to, rectification of or erasure of personal
    data concerning you, to object to or request restriction of processing, and to request data
    portability. You also have the right to lodge a complaint with the Swedish Authority for Privacy
    Protection (IMY).
</p>

<h2>Contact</h2>
